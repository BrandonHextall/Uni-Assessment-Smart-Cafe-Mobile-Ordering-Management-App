    canNavigateBack: Boolean,
    actions: @Composable () -> Unit = {}
) {
    val isDarkMode = isDarkModeEnabled()

    if (canNavigateBack) {
        TopAppBar(
            title = {
                Text(text = title)
            },
            actions = { actions() },
            navigationIcon = {
                /*IconButton(onClick = navigateUp) {
